const COUNTRY_NAME_BY_CODE: ReadonlyMap<string, string> = new Map(COUNTRIES.map((c) => [c.code, c.name]))

/** True when `code` is a known country code (case-sensitive: pass uppercase). */
export function isCountryCode(code: string): boolean {
  return COUNTRY_NAME_BY_CODE.has(code)
}

/** English name for a country code, or the code itself when unknown. */
export function countryName(code: string): string {
  return COUNTRY_NAME_BY_CODE.get(code.toUpperCase()) ?? code
}

